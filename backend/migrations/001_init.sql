CREATE TABLE groups (
  group_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            varchar(80)  NOT NULL,
  admission_year  integer      NOT NULL CHECK (admission_year BETWEEN 2000 AND 2100),
  course          integer      NOT NULL CHECK (course BETWEEN 1 AND 6),
  faculty         varchar(200) NOT NULL,
  specialty       varchar(200) NOT NULL,
  status          varchar(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','graduated')),
  graduated_at    timestamptz,
  graduation_year integer
);
CREATE UNIQUE INDEX groups_active_name_uq ON groups (faculty, name) WHERE status = 'active';

CREATE TABLE users (
  user_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name           varchar(200) NOT NULL CHECK (char_length(full_name) >= 3),
  email               varchar(254) NOT NULL UNIQUE CHECK (email = lower(email)),
  role                varchar(20)  NOT NULL CHECK (role IN ('student','teacher','curator','dean','admin')),
  status              varchar(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','graduated')),
  student_status      varchar(20)  CHECK (student_status IN ('active','graduated','repeat_pending')),
  group_id            integer REFERENCES groups(group_id),
  faculty             varchar(200),
  graduated_at        timestamptz,
  repeat_of_group_id  integer REFERENCES groups(group_id),
  repeat_started_at   timestamptz,
  password_hash       text,
  password_changed_at timestamptz,
  failed_attempts     integer     NOT NULL DEFAULT 0,
  locked_until        timestamptz,
  google_sub          varchar(64) UNIQUE,
  created_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX users_group_idx ON users (group_id);

CREATE TABLE user_roles (
  user_id integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  role    varchar(20) NOT NULL CHECK (role IN ('student','teacher','curator','dean','admin')),
  position integer NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, role)
);
CREATE TABLE curator_groups (
  user_id  integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  group_id integer NOT NULL REFERENCES groups(group_id),
  position integer NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, group_id)
);

CREATE TABLE streams (
  stream_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         varchar(120) NOT NULL,
  status       varchar(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','graduated')),
  graduated_at timestamptz
);
CREATE TABLE stream_groups (
  stream_id integer NOT NULL REFERENCES streams(stream_id) ON DELETE CASCADE,
  group_id  integer NOT NULL REFERENCES groups(group_id),
  position integer NOT NULL DEFAULT 0,
  PRIMARY KEY (stream_id, group_id)
);

CREATE TABLE semesters (
  semester_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_year varchar(9) NOT NULL CHECK (academic_year ~ '^\d{4}/\d{4}$'),
  term_number   integer    NOT NULL CHECK (term_number IN (1,2)),
  start_date    date       NOT NULL,
  end_date      date       NOT NULL,
  is_current    boolean    NOT NULL DEFAULT false,
  UNIQUE (academic_year, term_number),
  CHECK (start_date < end_date)
);

CREATE TABLE disciplines (
  discipline_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                varchar(200) NOT NULL CHECK (char_length(name) >= 3),
  description         text         NOT NULL DEFAULT '' CHECK (char_length(description) <= 2000),
  syllabus_url        varchar(2048) NOT NULL DEFAULT '',
  credits             integer      NOT NULL CHECK (credits BETWEEN 1 AND 30),
  semester_number     integer      NOT NULL CHECK (semester_number BETWEEN 1 AND 12),
  is_elective         boolean      NOT NULL DEFAULT false,
  catalog             integer      CHECK (catalog IN (1,2,3)),
  capacity            integer      CHECK (capacity IS NULL OR capacity >= 1),
  enrollment_start    date,
  enrollment_deadline date,
  status              varchar(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  CHECK (NOT is_elective OR (catalog IS NOT NULL AND capacity IS NOT NULL))
);

CREATE TABLE teaching_assignments (
  assignment_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id               integer NOT NULL REFERENCES users(user_id),
  discipline_id            integer NOT NULL REFERENCES disciplines(discipline_id),
  group_id                 integer REFERENCES groups(group_id),
  stream_id                integer REFERENCES streams(stream_id),
  semester_id              integer NOT NULL REFERENCES semesters(semester_id),
  course_at_assignment     integer NOT NULL CHECK (course_at_assignment BETWEEN 1 AND 6),
  target_name_at_assignment varchar(200),
  CHECK ((group_id IS NULL) <> (stream_id IS NULL))
);
CREATE TABLE assignment_groups (
  assignment_id integer NOT NULL REFERENCES teaching_assignments(assignment_id) ON DELETE CASCADE,
  group_id      integer NOT NULL REFERENCES groups(group_id),
  group_name    varchar(80),
  position integer NOT NULL DEFAULT 0,
  PRIMARY KEY (assignment_id, group_id)
);
CREATE TABLE assignment_roster (
  assignment_id integer NOT NULL REFERENCES teaching_assignments(assignment_id) ON DELETE CASCADE,
  student_id    integer NOT NULL REFERENCES users(user_id),
  group_id      integer NOT NULL REFERENCES groups(group_id),
  position integer NOT NULL DEFAULT 0,
  PRIMARY KEY (assignment_id, student_id)
);

CREATE TABLE weight_schemes (
  scheme_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discipline_id integer NOT NULL REFERENCES disciplines(discipline_id),
  course        integer NOT NULL CHECK (course BETWEEN 1 AND 6),
  semester_id   integer NOT NULL REFERENCES semesters(semester_id),
  updated_by    integer REFERENCES users(user_id),
  updated_at    timestamptz,
  UNIQUE (discipline_id, course, semester_id)
);
CREATE TABLE weight_scheme_items (
  scheme_id   integer NOT NULL REFERENCES weight_schemes(scheme_id) ON DELETE CASCADE,
  lesson_type varchar(80) NOT NULL,
  weight      integer NOT NULL CHECK (weight BETWEEN 0 AND 100),
  PRIMARY KEY (scheme_id, lesson_type)
);

CREATE TABLE lessons (
  lesson_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id     integer NOT NULL REFERENCES teaching_assignments(assignment_id),
  group_id          integer REFERENCES groups(group_id),
  lesson_date       date    NOT NULL,
  lesson_type       varchar(80) NOT NULL,
  max_score         integer NOT NULL DEFAULT 100 CHECK (max_score BETWEEN 1 AND 100),
  topic             varchar(160) NOT NULL CHECK (char_length(topic) >= 3),
  approved_by       integer REFERENCES users(user_id),
  retroactive_reason varchar(255)
);
CREATE INDEX lessons_assignment_idx ON lessons (assignment_id);

CREATE TABLE grades (
  grade_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  integer NOT NULL REFERENCES users(user_id),
  lesson_id   integer NOT NULL REFERENCES lessons(lesson_id),
  value       integer NOT NULL CHECK (value BETWEEN 0 AND 100),
  recorded_by integer REFERENCES users(user_id),
  approved_by integer REFERENCES users(user_id),
  given_at    timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, lesson_id)
);
CREATE TABLE grade_history (
  history_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grade_id     integer NOT NULL REFERENCES grades(grade_id),
  old_value    integer NOT NULL,
  new_value    integer NOT NULL,
  changed_by   integer NOT NULL REFERENCES users(user_id),
  requested_by integer REFERENCES users(user_id),
  changed_at   timestamptz NOT NULL DEFAULT now(),
  reason       varchar(255) NOT NULL
);
CREATE TABLE grade_correction_requests (
  request_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id      integer NOT NULL REFERENCES lessons(lesson_id),
  student_id     integer NOT NULL REFERENCES users(user_id),
  proposed_value integer NOT NULL CHECK (proposed_value BETWEEN 0 AND 100),
  previous_value integer,
  reason         varchar(255) NOT NULL,
  requested_by   integer NOT NULL REFERENCES users(user_id),
  requested_at   timestamptz NOT NULL DEFAULT now(),
  status         varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reviewed_by    integer REFERENCES users(user_id),
  reviewed_at    timestamptz
);
CREATE UNIQUE INDEX grade_correction_pending_uq ON grade_correction_requests (lesson_id, student_id) WHERE status = 'pending';

CREATE TABLE attendance (
  attendance_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    integer NOT NULL REFERENCES users(user_id),
  lesson_id     integer NOT NULL REFERENCES lessons(lesson_id),
  status        varchar(20) NOT NULL DEFAULT 'unmarked' CHECK (status IN ('unmarked','present','absent')),
  reason        varchar(20) CHECK (reason IN ('поважна','неповажна')),
  UNIQUE (student_id, lesson_id)
);

CREATE TABLE debts (
  debt_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    integer NOT NULL REFERENCES users(user_id),
  discipline_id integer NOT NULL REFERENCES disciplines(discipline_id),
  semester_id   integer NOT NULL REFERENCES semesters(semester_id),
  reason        varchar(500) NOT NULL,
  deadline      date,
  status        varchar(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
  source        varchar(20) NOT NULL DEFAULT 'automatic',
  created_at    timestamptz NOT NULL DEFAULT now(),
  closed_at     timestamptz,
  UNIQUE (student_id, discipline_id, semester_id)
);

CREATE TABLE elective_enrollments (
  enrollment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    integer NOT NULL REFERENCES users(user_id),
  discipline_id integer NOT NULL REFERENCES disciplines(discipline_id),
  semester_id   integer NOT NULL REFERENCES semesters(semester_id),
  status        varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  enrolled_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, discipline_id, semester_id)
);
CREATE TABLE elective_limits (
  limit_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id         integer NOT NULL UNIQUE REFERENCES groups(group_id),
  catalog1_credits integer NOT NULL CHECK (catalog1_credits BETWEEN 0 AND 60),
  catalog2_credits integer NOT NULL CHECK (catalog2_credits BETWEEN 0 AND 60),
  max_disciplines  integer NOT NULL CHECK (max_disciplines BETWEEN 0 AND 30),
  updated_by       integer REFERENCES users(user_id),
  updated_at       timestamptz
);

CREATE TABLE notifications (
  notification_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         integer NOT NULL REFERENCES users(user_id),
  message         text    NOT NULL,
  is_read         boolean NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user_idx ON notifications (user_id);

CREATE TABLE audit_logs (
  audit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id integer REFERENCES users(user_id),
  action   varchar(80) NOT NULL,
  target   varchar(255),
  detail   text,
  at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE group_promotions (
  promotion_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id      integer REFERENCES users(user_id),
  at            timestamptz NOT NULL DEFAULT now(),
  group_ids     jsonb NOT NULL,
  academic_year varchar(9) NOT NULL,
  rows          jsonb NOT NULL
);
CREATE TABLE graduations (
  graduation_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id        integer REFERENCES users(user_id),
  at              timestamptz NOT NULL DEFAULT now(),
  academic_year   varchar(9) NOT NULL,
  graduation_year integer    NOT NULL,
  course          integer    NOT NULL,
  group_ids       jsonb NOT NULL,
  rows            jsonb NOT NULL,
  streams         jsonb NOT NULL
);

CREATE TABLE recovery_codes (
  code_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  code_hash  text    NOT NULL,
  created_by integer REFERENCES users(user_id),
  created_at timestamptz NOT NULL DEFAULT now(),
  used_at    timestamptz
);
CREATE INDEX recovery_codes_user_idx ON recovery_codes (user_id) WHERE used_at IS NULL;

CREATE TABLE sessions (
  jti        uuid PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  role       varchar(20) NOT NULL,
  method     varchar(20) NOT NULL,
  issued_at  timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz
);

CREATE TABLE login_events (
  event_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer REFERENCES users(user_id) ON DELETE SET NULL,
  email      varchar(254),
  method     varchar(20) NOT NULL,
  success    boolean NOT NULL,
  reason     varchar(120),
  ip         varchar(64),
  user_agent varchar(300),
  at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX login_events_user_idx ON login_events (user_id, at DESC);
