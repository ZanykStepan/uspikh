export const defaultScale = (type) => type.endsWith(" 12") ? 12 : 100;
export const normalizedGrade = (grade, lesson) => {
  if (!grade || !lesson) return null;
  const maximum = lesson.max_score || 100;
  return Math.round((grade.value / maximum * 100) * 10) / 10;
};

